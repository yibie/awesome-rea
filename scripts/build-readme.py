#!/usr/bin/env python3
"""Generate README.md for awesome-rea from the files in categories/.

README.md is a build artefact. Edit categories/*.md, then run this script.
The prose that is not a table lives here, not in README.md, so that a rebuild
never drops it.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
README_PATH = REPO_ROOT / "README.md"

# Each entry lives in exactly one category, chosen by what the project is.
CATEGORIES = [
    ("game-decompilation.md", "Game Decompilation"),
    ("static-recompilation-native-ports.md", "Static Recompilation & Native Ports"),
    ("tooling-and-mcp.md", "Tooling & MCP"),
    ("related-practices-discussions.md", "Related Practices & Discussions"),
]
# Seeded but not yet qualifying: kept off the front page so an empty category
# never reads as a claim.
OPEN_TRACKING = [
    ("console-and-firmware.md", "Console & Firmware"),
]
ALL_FILES = CATEGORIES + OPEN_TRACKING

# - [Name](URL) - Domain: what the AI does, and what accepts the result.
ENTRY_RE = re.compile(r"^(- \[[^\]]+\]\([^)]+\))\s*-\s*(.+)$")
REPO_RE = re.compile(r"https?://github\.com/([^/\s)]+)/([^/\s)#]+)")
STAR_LABEL = "%E2%98%85"  # a star, escaped for the shields.io path


def star_badge(line: str) -> str:
    """Append a live star badge for GitHub links. Nothing is baked in.

    The count comes from shields.io at render time, so the list cannot drift
    from the repository it points at, and no number has to be re-verified by
    hand. Sub-paths collapse to the repository root.
    """
    m = ENTRY_RE.match(line)
    if not m:
        return line
    repo = REPO_RE.search(m.group(1))
    if not repo:
        return line
    owner, name = repo.group(1), repo.group(2)
    if name.endswith(".git"):
        name = name[:-4]
    url = (
        f"https://img.shields.io/github/stars/{owner}/{name}"
        f"?style=flat-square&label={STAR_LABEL}"
    )
    return f"{m.group(1)} ![stars]({url}) - {m.group(2)}"


def load_categories() -> list[dict]:
    out = []
    for filename, title in ALL_FILES:
        path = REPO_ROOT / "categories" / filename
        if not path.exists():
            print(f"⚠️  parse: missing category file {filename}", file=sys.stderr)
            continue
        raw = path.read_text(encoding="utf-8").split("\n")
        entries, description = [], []
        for line in raw:
            if line.startswith("# "):
                continue
            if line.startswith("- ["):
                entries.append(line)
            elif line.strip() and not entries:
                description.append(line.strip())
        out.append(
            {
                "file": filename,
                "title": title,
                "description": description,
                "entries": entries,
                "rendered": [],
            }
        )
    return out


def audit(blocks: list[dict]) -> list[str]:
    """Report lines that look like entries but do not match the format.

    A malformed line is still rendered, so a count comparison cannot catch it;
    only the per-line check can.
    """
    warnings = []
    for block in blocks:
        path = REPO_ROOT / "categories" / block["file"]
        for line in path.read_text(encoding="utf-8").split("\n"):
            if not line.startswith("- "):
                continue
            if "md) —" in line or "entries" in line:
                continue
            if not ENTRY_RE.match(line):
                warnings.append(
                    f"⚠️  parse: entry line does not match the entry format — {line[:90]}"
                )
    return warnings


def check_duplicates(blocks: list[dict]) -> list[str]:
    seen: dict[str, str] = {}
    problems = []
    for block in blocks:
        for line in block["entries"]:
            url = re.search(r"\(([^)]+)\)", line)
            if not url:
                continue
            key = url.group(1).rstrip("/").lower()
            if key in seen:
                problems.append(
                    f"⚠️  duplicate: {key} appears in {seen[key]} and {block['file']}"
                )
            seen[key] = block["file"]
    return problems


def github_anchor(title: str) -> str:
    return "#" + re.sub(r"[^a-z0-9 -]", "", title.lower()).replace(" ", "-")


README_HEADER = """# awesome-rea

<!-- Generated by scripts/build-readme.py. Edit category files, then rebuild README. -->

A curated list of AI-assisted reverse engineering: decompilation, static recompilation, native ports, and the agent tooling around them.

Every entry answers the same question: **how does this project define "done"?** This is not a collection of "AI is impressive" demos. It is a collection of projects that turned correctness into a gate a machine can decide — a byte comparison against the original ROM, a required hash match on the user's own dump, a compatibility matrix, a build that has to stay green.

## Why this list

The interesting part of an AI-assisted decompilation is never that a model wrote code. It is that someone decided what counts as correct *before* letting agents iterate, and then built the harness that decides it. That decision is what separates a project that finishes from one that produces plausible-looking source nobody can trust.

So a project with no stated acceptance test is not listed here, however impressive its demo.

## Inclusion criteria

An entry qualifies only if all of the following hold:

1. **Public and citable.** A reachable repository, write-up or public thread. Anything behind a paywall, a login, or a dead link does not go in.
2. **AI or LLM agents did identifiable work.** Not "AI could be used here" — an agent wrote functions, hunted root causes, wrote tests, ran verification, or played a verifier role. Generic reverse engineering with no agent in the loop is out of scope.
3. **The acceptance test is stated.** One sentence has to make the verification visible: what is compared, against what, and what has to pass. If the entry cannot say how correctness is decided, it belongs in Related Practices & Discussions, or it waits.
4. **One category per entry**, chosen by what the project *is*, not by which company made it.

Explicitly not accepted: vendor announcements, opinion pieces with no artifact behind them, sources that cannot be reached, and entries where "AI-powered" is marketing copy rather than a description of work.

## Curation is not endorsement

> **A listing is not an endorsement.** This project applies *inclusion* rules only — publicly citable, AI work identifiable, acceptance test stated. Inclusion says nothing about quality, legality in your jurisdiction, or whether a project will ever finish.

> **Treat same-day bulk submissions with particular care.** Several repositories publishing on the same day, sharing a README template, a scaffold, or a single-commit history, are usually one project family rather than independent work. They count as one submission, and the list counts them once.

## Legal & ethics notes

This corner of AI-assisted work sits closer to licence law than most, so read this before using anything here.

- **Native ports do not include the original assets.** Ports listed here are built from source that reimplements game logic; they still require you to own the game, and they ship no ROMs, textures, audio or data.
- **Matching decompilation is a clean-room reimplementation.** It reconstructs behaviour into new source and does not redistribute the original code. The legal position of publishing such source varies by project and jurisdiction, and is not settled everywhere.
- **"Reverse engineer anything" tools carry real EULA and DMCA risk.** Where an entry describes a tool used on a commercial product you did not licence for that purpose, that is a factual description of what someone did, not advice that you may.
- **Nothing here is legal advice, and a listing is not approval.** If you intend to ship something built from an entry on this list, check the licence, the local rules, and the terms you agreed to yourself.

## Current coverage
"""

README_MIDDLE = """Each entry lives in exactly one category, chosen by what the project is. The README is generated from the category files, so this page is always the current state of the list.

## Browse by category

"""

README_PRIVATE_NOTE = """## Open categories still being seeded

The categories below are tracked but deliberately empty: they stay off the front page until a qualifying entry exists, so that an empty category never reads as a claim.

"""


def render_readme(blocks: list[dict], total: int) -> str:
    open_files = {f for f, _ in OPEN_TRACKING}
    front = [b for b in blocks if b["file"] not in open_files]
    behind = [b for b in blocks if b["file"] in open_files]
    out = [README_HEADER]
    out.append("")
    out.append("| Category | Entries |")
    out.append("| --- | ---: |")
    for block in front:
        n = len(block["rendered"])
        out.append(f"| [{block['title']}]({github_anchor(block['title'])}) | {n} |")
    out.append(f"| **Total** | **{total}** |")
    out.append("")
    out.append(README_MIDDLE.rstrip())
    for block in front:
        out.append(f"- [{block['title']}]({github_anchor(block['title'])}) — {len(block['rendered'])} entries")
    out.append("")
    out.append("## Full list")
    for block in front:
        out.append("")
        out.append(f"### {block['title']}")
        out.append("")
        for para in block["description"]:
            out.append(para)
        out.append("")
        for line in block["rendered"]:
            out.append(line)
    if behind:
        out.append("")
        out.append(README_PRIVATE_NOTE.rstrip())
        for block in behind:
            out.append(f"- **{block['title']}** — tracked, no qualifying entries yet")
    out.append("")
    return "\n".join(out) + "\n"


def main() -> int:
    blocks = load_categories()

    warnings = audit(blocks)
    duplicates = check_duplicates(blocks)

    total = 0
    for block in blocks:
        for line in block["entries"]:
            block["rendered"].append(star_badge(line))
            total += 1
        if block["file"] not in {f for f, _ in OPEN_TRACKING}:
            if not block["entries"]:
                warnings.append(f"⚠️  parse: {block['file']} has no entries but is on the front page")

    for w in warnings:
        print(w)
    for d in duplicates:
        print(d)
    if duplicates:
        print("duplicate sources: refusing to write README")
        return 1

    README_PATH.write_text(render_readme(blocks, total), encoding="utf-8")
    print(f"README.md written: {total} entries across {len(CATEGORIES)} categories")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
